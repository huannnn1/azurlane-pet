const { contextBridge, ipcRenderer } = require('electron')

contextBridge.exposeInMainWorld('pet', {
  hit: (v) => ipcRenderer.send('pet:hit', !!v),
  dragStart: (p) => ipcRenderer.send('pet:drag-start', p),
  dragMove: (p) => ipcRenderer.send('pet:drag-move', p),
  dragEnd: () => ipcRenderer.send('pet:drag-end'),
  quit: () => ipcRenderer.send('pet:quit'),
  hide: () => ipcRenderer.send('pet:hide'),
  interactive: (rects) => ipcRenderer.send('pet:interactive', rects),
  menu: () => ipcRenderer.send('pet:menu'),
  usage: () => ipcRenderer.invoke('pet:usage'),
  usageDetail: () => ipcRenderer.invoke('pet:usage-detail'),
  openUsage: () => ipcRenderer.send('pet:open-usage'),
  closeUsage: () => ipcRenderer.send('pet:close-usage'),
  skinsDetail: () => ipcRenderer.invoke('pet:skins-detail'),
  setSkin: (dir) => ipcRenderer.invoke('pet:set-skin', dir),
  toggleFav: (dir) => ipcRenderer.invoke('pet:toggle-fav', dir),
  openSkins: () => ipcRenderer.send('pet:open-skins'),
  closeSkins: () => ipcRenderer.send('pet:close-skins'),
  balance: () => ipcRenderer.invoke('pet:balance'),
  config: () => ipcRenderer.invoke('pet:config'),
  skin: () => ipcRenderer.invoke('pet:skin'),
  skins: () => ipcRenderer.invoke('pet:skins'),
  fit: () => ipcRenderer.invoke('pet:fit'),
  hitareas: (skin) => ipcRenderer.invoke('pet:hitareas', skin),
  saveHitareas: (skin, data) => ipcRenderer.invoke('pet:save-hitareas', skin, data),
  clearHitareas: (skin) => ipcRenderer.invoke('pet:clear-hitareas', skin),
  onSkin: (cb) => ipcRenderer.on('pet:skin-changed', (_e, rel) => cb(rel)),
  onAssetsChanged: (cb) => ipcRenderer.on('pet:assets-changed', (_e, rel) => cb(rel)),
  chooseAssets: () => ipcRenderer.send('pet:choose-assets'),
  onFit: (cb) => ipcRenderer.on('pet:fit-changed', (_e, m) => cb(m)),
  onCalibrate: (cb) => ipcRenderer.on('pet:calibrate', () => cb()),
  onHitareasCleared: (cb) => ipcRenderer.on('pet:hitareas-cleared', () => cb()),
  onActivity: (cb) => ipcRenderer.on('pet:activity', (_e, active) => cb(active)),
  onVisible: (cb) => ipcRenderer.on('pet:visible', (_e, v) => cb(v)),
  onNoSkins: (cb) => ipcRenderer.on('pet:no-skins', () => cb()),
  skinOk: (skin) => ipcRenderer.send('pet:skin-ok', skin),
  skinFailed: (skin) => ipcRenderer.send('pet:skin-failed', skin),
})
